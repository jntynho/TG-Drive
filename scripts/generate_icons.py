#!/usr/bin/env python3
"""Generate native Compose icons from the vendored Solar Linear SVG subset (offline)."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as E

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/solar'

def number(value):
    return f'{float(value):g}'

def path_for(element):
    tag = element.tag.split('}')[-1]
    a = element.attrib
    if tag == 'path':
        return a['d']
    if tag in ('polyline', 'polygon'):
        return 'M' + a['points'] + ('Z' if tag == 'polygon' else '')
    if tag == 'line':
        return f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}"
    if tag in ('circle', 'ellipse'):
        x, y = float(a.get('cx', 0)), float(a.get('cy', 0))
        rx, ry = float(a.get('r', a.get('rx', 0))), float(a.get('r', a.get('ry', 0)))
        return f'M{x-rx:g},{y:g}a{rx:g},{ry:g} 0 1 0 {2*rx:g},0a{rx:g},{ry:g} 0 1 0 {-2*rx:g},0Z'
    raise ValueError(f'Unsupported SVG shape: {tag}')

def paths(element, inherited=None):
    attrs = dict(inherited or {})
    attrs.update(element.attrib)
    # Rotation about its own center leaves a circle unchanged (Solar's dots/tag hole).
    if 'transform' in attrs and element.tag.split('}')[-1] == 'circle':
        rotation = re.fullmatch(r'rotate\(([-\d.]+) ([-\d.]+) ([-\d.]+)\)', attrs['transform'])
        if rotation and float(rotation[2]) == float(attrs.get('cx', 0)) and float(rotation[3]) == float(attrs.get('cy', 0)):
            attrs.pop('transform')
    forbidden = {'transform', 'clip-path', 'mask', 'filter', 'stroke-dasharray', 'style'} & attrs.keys()
    if forbidden:
        raise ValueError(f'Unsupported SVG attributes: {forbidden}')
    tag = element.tag.split('}')[-1]
    if tag in ('svg', 'g'):
        for child in element:
            yield from paths(child, attrs)
    else:
        yield path_for(element), attrs

def brush(value):
    if value == 'none':
        return 'null'
    if value in ('currentColor', '#000', '#000000', 'black'):
        return 'SolidColor(Color.Black)'
    raise ValueError(f'Unexpected SVG color: {value}')

def float_literal(value):
    return number(value) + 'f'

aliases = json.loads((SOURCE / 'aliases.json').read_text())
canonical = {icon: 'solar' + ''.join(part.title() for part in icon.split('-')) for icon in set(aliases.values())}
lines = ['''// Generated by scripts/generate_icons.py; edit third_party/solar sources instead.
package app.tgdrive.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** Solar Linear by 480 Design, CC BY 4.0; attribution and source in third_party/solar. */
object DriveIcons {''']
for alias, icon in aliases.items():
    lines.append(f'    val {alias}: ImageVector get() = {canonical[icon]}')
for icon in sorted(canonical):
    svg = E.parse(SOURCE / 'icons' / f'{icon}.svg').getroot()
    assert svg.attrib['viewBox'] == '0 0 24 24'
    lines.append(f'    private val {canonical[icon]}: ImageVector by lazy {{\n        ImageVector.Builder("solar:{icon}",24.dp,24.dp,24f,24f).apply {{')
    for data, attrs in paths(svg):
        fill = brush(attrs.get('fill', 'black'))
        stroke = brush(attrs.get('stroke', 'none'))
        width = float(attrs.get('stroke-width', 1))
        if stroke != 'null':
            assert width in (1, 1.5), (icon, width)  # Preserve the source's small sparkle detail too.
        cap = {'round':'Round', 'square':'Square', 'butt':'Butt'}[attrs.get('stroke-linecap', 'butt')]
        join = {'round':'Round', 'bevel':'Bevel', 'miter':'Miter'}[attrs.get('stroke-linejoin', 'miter')]
        alpha = float(attrs.get('opacity', 1))
        fill_alpha = alpha * float(attrs.get('fill-opacity', 1))
        stroke_alpha = alpha * float(attrs.get('stroke-opacity', 1))
        fill_type = 'EvenOdd' if attrs.get('fill-rule') == 'evenodd' else 'NonZero'
        lines.append('            addPath(PathParser().parsePathString(' + json.dumps(data) + ').toNodes(),'
            + f'fill={fill},stroke={stroke},strokeLineWidth={float_literal(width)},'
            + f'strokeLineCap=StrokeCap.{cap},strokeLineJoin=StrokeJoin.{join},'
            + f'pathFillType=PathFillType.{fill_type},fillAlpha={float_literal(fill_alpha)},strokeAlpha={float_literal(stroke_alpha)})')
    lines.append('        }.build()\n    }')
lines.append('}\n')
(ROOT / 'app/src/main/java/app/tgdrive/ui/DriveIcons.kt').write_text('\n'.join(lines))
print(f'Generated {len(canonical)} Solar Linear icons, {len(aliases)} semantic aliases.')
